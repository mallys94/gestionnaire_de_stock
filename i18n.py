def tr(key: str, **kwargs) -> str:
    """Return the localized string for ``key``, applying replacement params."""
    table = _TRANSLATIONS.get(_current_lang, _TRANSLATIONS[DEFAULT_LANGUAGE])
    template = table.get(key)
    if template is None:
        template = _TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError):
            return template
    return template


def set_language(lang: str) -> None:
    """Set the active UI language (e.g. 'en', 'fr', 'de', 'es')."""
    global _current_lang
    if lang in _TRANSLATIONS:
        _current_lang = lang


def get_language() -> str:
    """Return the currently active language code."""
    return _current_lang


def save_language(lang: str) -> None:
    """Persist the chosen language using QSettings."""
    settings = QSettings(_ORG, _APP)
    settings.setValue("language", lang)


def load_language() -> str:
    """Load the last saved language (falls back to the default)."""
    settings = QSettings(_ORG, _APP)
    lang = settings.value("language", DEFAULT_LANGUAGE, str)
    return lang if lang in _TRANSLATIONS else DEFAULT_LANGUAGE